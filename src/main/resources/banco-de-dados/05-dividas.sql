-- =====================================================================
-- 05-dividas.sql - Modulo 05 - Gestao de Dividas (Grupo 9)
-- Prefixo das tabelas: TB_DIV_
-- Ordem de criacao: TB_DIV_TIPO -> TB_DIV_DIVIDA -> TB_DIV_PARCELA
-- ID_PESSOA referencia TB_PES_USUARIO (modulo 01) e ID_CONTA referencia
-- TB_CTA_CONTA (modulo 02). Os IDs recebem o UUID gerado pela aplicacao.
-- =====================================================================

CREATE TABLE TB_DIV_TIPO (
    ID         VARCHAR2(36)   NOT NULL,
    NOME       VARCHAR2(100)  NOT NULL,
    DESCRICAO  VARCHAR2(255),
    CONSTRAINT PK_DIV_TIPO PRIMARY KEY (ID),
    CONSTRAINT UK_DIV_TIPO_NOME UNIQUE (NOME)
);

CREATE TABLE TB_DIV_DIVIDA (
    ID                VARCHAR2(36)   NOT NULL,
    ID_TIPO           VARCHAR2(36)   NOT NULL,
    ID_PESSOA         VARCHAR2(36)   NOT NULL,
    CREDOR            VARCHAR2(150)  NOT NULL,
    DESCRICAO         VARCHAR2(255),
    VALOR_TOTAL       NUMBER(15,2)   NOT NULL,
    TAXA_JUROS        NUMBER(5,2)    DEFAULT 0 NOT NULL,
    DATA_CONTRATACAO  DATE           NOT NULL,
    QTD_PARCELAS      NUMBER(10)     NOT NULL,
    STATUS            VARCHAR2(20)   DEFAULT 'ATIVA' NOT NULL,
    CRIADO_EM         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DIV_DIVIDA PRIMARY KEY (ID),
    CONSTRAINT FK_DIV_DIVIDA_TIPO FOREIGN KEY (ID_TIPO) REFERENCES TB_DIV_TIPO (ID),
    CONSTRAINT FK_DIV_DIVIDA_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES TB_PES_USUARIO (ID),
    CONSTRAINT CK_DIV_DIVIDA_VALOR CHECK (VALOR_TOTAL > 0),
    CONSTRAINT CK_DIV_DIVIDA_JUROS CHECK (TAXA_JUROS >= 0),
    CONSTRAINT CK_DIV_DIVIDA_PARCELAS CHECK (QTD_PARCELAS > 0),
    CONSTRAINT CK_DIV_DIVIDA_STATUS CHECK (STATUS IN ('ATIVA', 'QUITADA', 'ATRASADA', 'CANCELADA'))
);

CREATE TABLE TB_DIV_PARCELA (
    ID               VARCHAR2(36)  NOT NULL,
    ID_DIVIDA        VARCHAR2(36)  NOT NULL,
    ID_CONTA         VARCHAR2(36),
    NUMERO           NUMBER(10)    NOT NULL,
    VALOR            NUMBER(15,2)  NOT NULL,
    DATA_VENCIMENTO  DATE          NOT NULL,
    DATA_PAGAMENTO   DATE,
    STATUS           VARCHAR2(20)  DEFAULT 'PENDENTE' NOT NULL,
    CONSTRAINT PK_DIV_PARCELA PRIMARY KEY (ID),
    CONSTRAINT FK_DIV_PARCELA_DIVIDA FOREIGN KEY (ID_DIVIDA) REFERENCES TB_DIV_DIVIDA (ID),
    CONSTRAINT FK_DIV_PARCELA_CONTA FOREIGN KEY (ID_CONTA) REFERENCES TB_CTA_CONTA (ID),
    CONSTRAINT UK_DIV_PARCELA_NUMERO UNIQUE (ID_DIVIDA, NUMERO),
    CONSTRAINT CK_DIV_PARCELA_NUMERO CHECK (NUMERO > 0),
    CONSTRAINT CK_DIV_PARCELA_VALOR CHECK (VALOR > 0),
    CONSTRAINT CK_DIV_PARCELA_STATUS CHECK (STATUS IN ('PENDENTE', 'PAGA', 'ATRASADA')),
    CONSTRAINT CK_DIV_PARCELA_PAGAMENTO CHECK (
        (STATUS = 'PAGA' AND DATA_PAGAMENTO IS NOT NULL)
        OR (STATUS <> 'PAGA' AND DATA_PAGAMENTO IS NULL)
    )
);

COMMENT ON TABLE TB_DIV_TIPO IS 'Tipos de divida (cartao, financiamento, emprestimo etc.)';
COMMENT ON COLUMN TB_DIV_TIPO.NOME IS 'Nome do tipo de divida, unico';
COMMENT ON COLUMN TB_DIV_TIPO.DESCRICAO IS 'Descricao opcional do tipo de divida';

COMMENT ON TABLE TB_DIV_DIVIDA IS 'Dividas contraidas por uma pessoa';
COMMENT ON COLUMN TB_DIV_DIVIDA.ID_PESSOA IS 'Pessoa devedora (TB_PES_USUARIO, modulo 01)';
COMMENT ON COLUMN TB_DIV_DIVIDA.CREDOR IS 'Banco ou instituicao a quem se deve';
COMMENT ON COLUMN TB_DIV_DIVIDA.VALOR_TOTAL IS 'Valor total contratado da divida';
COMMENT ON COLUMN TB_DIV_DIVIDA.TAXA_JUROS IS 'Taxa de juros em percentual';
COMMENT ON COLUMN TB_DIV_DIVIDA.QTD_PARCELAS IS 'Quantidade de parcelas contratadas';
COMMENT ON COLUMN TB_DIV_DIVIDA.STATUS IS 'ATIVA, QUITADA, ATRASADA ou CANCELADA';

COMMENT ON TABLE TB_DIV_PARCELA IS 'Parcelas de uma divida';
COMMENT ON COLUMN TB_DIV_PARCELA.ID_CONTA IS 'Conta usada para pagar a parcela (TB_CTA_CONTA, modulo 02)';
COMMENT ON COLUMN TB_DIV_PARCELA.NUMERO IS 'Numero da parcela dentro da divida, a partir de 1';
COMMENT ON COLUMN TB_DIV_PARCELA.DATA_PAGAMENTO IS 'Preenchida somente quando a parcela esta PAGA';
COMMENT ON COLUMN TB_DIV_PARCELA.STATUS IS 'PENDENTE, PAGA ou ATRASADA';

