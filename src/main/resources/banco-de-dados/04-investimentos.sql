-- Perfil de investidor de uma pessoa (suitability). Uma pessoa tem no maximo um perfil.
CREATE TABLE TB_INV_INVESTIDOR (
    ID          VARCHAR2(36)   NOT NULL,
    ID_PESSOA   VARCHAR2(36)   NOT NULL,
    PERFIL      VARCHAR2(20)   NOT NULL,
    OBJETIVO    VARCHAR2(150),
    CRIADO_EM   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INV_INVESTIDOR PRIMARY KEY (ID),
    CONSTRAINT UK_INV_INVESTIDOR_PESSOA UNIQUE (ID_PESSOA),
    CONSTRAINT FK_INV_INVESTIDOR_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES TB_PES_USUARIO (ID),
    CONSTRAINT CK_INV_INVESTIDOR_PERFIL CHECK (PERFIL IN ('CONSERVADOR', 'MODERADO', 'ARROJADO'))
);

-- Aplicacao financeira de um investidor, feita a partir de uma conta bancaria.
CREATE TABLE TB_INV_APLICACAO (
    ID               VARCHAR2(36)   NOT NULL,
    ID_INVESTIDOR    VARCHAR2(36)   NOT NULL,
    ID_CONTA         VARCHAR2(36)   NOT NULL,
    DESCRICAO        VARCHAR2(150)  NOT NULL,
    TIPO             VARCHAR2(30)   NOT NULL,
    VALOR_APLICADO   NUMBER(15,2)   NOT NULL,
    TAXA_ANUAL       NUMBER(6,2)    NOT NULL,
    DATA_APLICACAO   DATE           NOT NULL,
    DATA_VENCIMENTO  DATE,
    STATUS           VARCHAR2(20)   DEFAULT 'ATIVA' NOT NULL,
    CRIADO_EM        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INV_APLICACAO PRIMARY KEY (ID),
    CONSTRAINT FK_INV_APLICACAO_INVESTIDOR FOREIGN KEY (ID_INVESTIDOR) REFERENCES TB_INV_INVESTIDOR (ID),
    CONSTRAINT FK_INV_APLICACAO_CONTA FOREIGN KEY (ID_CONTA) REFERENCES TB_CTA_CONTA (ID),
    CONSTRAINT CK_INV_APLICACAO_TIPO CHECK (TIPO IN ('TESOURO_DIRETO', 'RENDA_FIXA', 'FUNDOS', 'ACOES', 'CRIPTOMOEDAS')),
    CONSTRAINT CK_INV_APLICACAO_STATUS CHECK (STATUS IN ('ATIVA', 'RESGATADA')),
    CONSTRAINT CK_INV_APLICACAO_VALOR CHECK (VALOR_APLICADO > 0),
    CONSTRAINT CK_INV_APLICACAO_TAXA CHECK (TAXA_ANUAL >= 0),
    CONSTRAINT CK_INV_APLICACAO_VENCIMENTO CHECK (DATA_VENCIMENTO IS NULL OR DATA_VENCIMENTO > DATA_APLICACAO)
);

COMMENT ON TABLE TB_INV_INVESTIDOR IS 'Perfil de investidor (suitability) de cada usuario';
COMMENT ON COLUMN TB_INV_INVESTIDOR.ID_PESSOA IS 'Usuario dono do perfil (TB_PES_USUARIO, modulo 01)';
COMMENT ON COLUMN TB_INV_INVESTIDOR.PERFIL IS 'CONSERVADOR, MODERADO ou ARROJADO: define o risco maximo permitido';
COMMENT ON TABLE TB_INV_APLICACAO IS 'Aplicacoes financeiras do investidor';
COMMENT ON COLUMN TB_INV_APLICACAO.ID_CONTA IS 'Conta de origem do dinheiro (TB_CTA_CONTA, modulo 02)';
COMMENT ON COLUMN TB_INV_APLICACAO.TAXA_ANUAL IS 'Rentabilidade esperada em % ao ano';
