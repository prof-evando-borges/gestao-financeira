-- =====================================================================
-- 02-contas.sql - Modulo 02 - Contas Bancarias (Grupo 2)
-- Prefixo das tabelas: TB_CTA_
-- Ordem de criacao: TB_CTA_BANCO -> TB_CTA_CONTA -> TB_CTA_CHAVE_PIX
-- ID_USUARIO referencia TB_PES_USUARIO (modulo 01).
-- TB_CTA_CONTA e referenciada por TB_DIV_PARCELA (modulo 05): o nome da
-- tabela e da chave primaria (ID) nao podem mudar.
-- Os IDs recebem o UUID gerado pela aplicacao.
-- =====================================================================

CREATE TABLE TB_CTA_BANCO (
    ID      VARCHAR2(36)   NOT NULL,
    CODIGO  VARCHAR2(3)    NOT NULL,
    NOME    VARCHAR2(100)  NOT NULL,
    CONSTRAINT PK_CTA_BANCO PRIMARY KEY (ID),
    CONSTRAINT UK_CTA_BANCO_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE TB_CTA_CONTA (
    ID                      VARCHAR2(36)   NOT NULL,
    ID_USUARIO              VARCHAR2(36)   NOT NULL,
    ID_BANCO                VARCHAR2(36)   NOT NULL,
    NUMERO_CONTA            VARCHAR2(20)   NOT NULL,
    AGENCIA                 VARCHAR2(10)   NOT NULL,
    TIPO                    VARCHAR2(20)   NOT NULL,
    SALDO                   NUMBER(15,2)   DEFAULT 0 NOT NULL,
    LIMITE_CHEQUE_ESPECIAL  NUMBER(15,2),
    TAXA_RENDIMENTO_MENSAL  NUMBER(5,2),
    STATUS                  VARCHAR2(20)   DEFAULT 'ATIVA' NOT NULL,
    DATA_ABERTURA           DATE           NOT NULL,
    DATA_ENCERRAMENTO       DATE,
    CONSTRAINT PK_CTA_CONTA PRIMARY KEY (ID),
    CONSTRAINT UK_CTA_CONTA_NUMERO UNIQUE (ID_BANCO, AGENCIA, NUMERO_CONTA),
    CONSTRAINT FK_CTA_CONTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_PES_USUARIO (ID),
    CONSTRAINT FK_CTA_CONTA_BANCO FOREIGN KEY (ID_BANCO) REFERENCES TB_CTA_BANCO (ID),
    CONSTRAINT CK_CTA_CONTA_TIPO CHECK (TIPO IN ('CORRENTE', 'POUPANCA')),
    CONSTRAINT CK_CTA_CONTA_STATUS CHECK (STATUS IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),
    CONSTRAINT CK_CTA_CONTA_LIMITE CHECK (
        LIMITE_CHEQUE_ESPECIAL IS NULL
        OR (TIPO = 'CORRENTE' AND LIMITE_CHEQUE_ESPECIAL >= 0)
    ),
    CONSTRAINT CK_CTA_CONTA_TAXA CHECK (
        TAXA_RENDIMENTO_MENSAL IS NULL
        OR (TIPO = 'POUPANCA' AND TAXA_RENDIMENTO_MENSAL >= 0)
    ),
    CONSTRAINT CK_CTA_CONTA_SALDO CHECK (SALDO >= -NVL(LIMITE_CHEQUE_ESPECIAL, 0)),
    CONSTRAINT CK_CTA_CONTA_ENCERRAMENTO CHECK (
        (STATUS = 'ENCERRADA' AND DATA_ENCERRAMENTO IS NOT NULL AND DATA_ENCERRAMENTO >= DATA_ABERTURA)
        OR (STATUS <> 'ENCERRADA' AND DATA_ENCERRAMENTO IS NULL)
    )
);

CREATE TABLE TB_CTA_CHAVE_PIX (
    ID         VARCHAR2(36)  NOT NULL,
    ID_CONTA   VARCHAR2(36)  NOT NULL,
    TIPO       VARCHAR2(20)  NOT NULL,
    VALOR      VARCHAR2(77)  NOT NULL,
    ATIVA      NUMBER(1)     DEFAULT 1 NOT NULL,
    CRIADO_EM  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CTA_CHAVE_PIX PRIMARY KEY (ID),
    CONSTRAINT UK_CTA_CHAVE_PIX_VALOR UNIQUE (VALOR),
    CONSTRAINT FK_CTA_CHAVE_PIX_CONTA FOREIGN KEY (ID_CONTA) REFERENCES TB_CTA_CONTA (ID),
    CONSTRAINT CK_CTA_CHAVE_PIX_TIPO CHECK (TIPO IN ('CPF', 'EMAIL', 'TELEFONE', 'ALEATORIA')),
    CONSTRAINT CK_CTA_CHAVE_PIX_ATIVA CHECK (ATIVA IN (0, 1))
);

COMMENT ON TABLE TB_CTA_BANCO IS 'Instituicoes financeiras onde as contas sao mantidas';
COMMENT ON COLUMN TB_CTA_BANCO.CODIGO IS 'Codigo COMPE do banco com 3 digitos (ex.: 001, 341)';
COMMENT ON COLUMN TB_CTA_BANCO.NOME IS 'Nome do banco';

COMMENT ON TABLE TB_CTA_CONTA IS 'Contas bancarias (corrente e poupanca) do usuario';
COMMENT ON COLUMN TB_CTA_CONTA.ID_USUARIO IS 'Titular da conta (TB_PES_USUARIO, modulo 01)';
COMMENT ON COLUMN TB_CTA_CONTA.ID_BANCO IS 'Banco da conta (TB_CTA_BANCO)';
COMMENT ON COLUMN TB_CTA_CONTA.TIPO IS 'CORRENTE ou POUPANCA';
COMMENT ON COLUMN TB_CTA_CONTA.SALDO IS 'Saldo atual; pode ficar negativo ate o limite do cheque especial';
COMMENT ON COLUMN TB_CTA_CONTA.LIMITE_CHEQUE_ESPECIAL IS 'Usado apenas em conta CORRENTE';
COMMENT ON COLUMN TB_CTA_CONTA.TAXA_RENDIMENTO_MENSAL IS 'Percentual ao mes, usado apenas em POUPANCA';
COMMENT ON COLUMN TB_CTA_CONTA.STATUS IS 'ATIVA, BLOQUEADA ou ENCERRADA';
COMMENT ON COLUMN TB_CTA_CONTA.DATA_ENCERRAMENTO IS 'Preenchida somente quando a conta esta ENCERRADA';

COMMENT ON TABLE TB_CTA_CHAVE_PIX IS 'Chaves Pix vinculadas a uma conta';
COMMENT ON COLUMN TB_CTA_CHAVE_PIX.ID_CONTA IS 'Conta que recebe pela chave (TB_CTA_CONTA)';
COMMENT ON COLUMN TB_CTA_CHAVE_PIX.TIPO IS 'CPF, EMAIL, TELEFONE ou ALEATORIA';
COMMENT ON COLUMN TB_CTA_CHAVE_PIX.VALOR IS 'Valor da chave, unico no sistema';
COMMENT ON COLUMN TB_CTA_CHAVE_PIX.ATIVA IS '1 = ativa, 0 = desativada';

